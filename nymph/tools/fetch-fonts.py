# -*- coding: utf-8 -*-
"""Fetch Fraunces + Inter woff2 subsets from the Google Fonts CSS API and
write a self-hosted assets/fonts/fonts.css. Latin and latin-ext subsets only
(the blog is English; zero CJK is a site-wide constraint).

Both families are requested as variable fonts: one file per style covers the
whole weight range, so the page ships four woff2 files instead of sixteen.

Run:  python nymph/tools/fetch-fonts.py
"""
import os
import re
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, "..", "assets", "fonts"))

UA = ("Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
      "(KHTML, like Gecko) Chrome/120.0 Safari/537.36")

KEEP_SUBSETS = {"latin", "latin-ext"}

# (css2 family query, file prefix)
FAMILIES = [
    ("family=Fraunces:ital,opsz,wght,SOFT,WONK"
     "@0,9..144,100..900,0..100,0..1"
     ";1,9..144,100..900,0..100,0..1", "fraunces"),
    ("family=Inter:wght@100..900", "inter"),
]

HEADER = ("/* self-hosted Fraunces + Inter, SIL OFL 1.1.\n"
          "   Generated by nymph/tools/fetch-fonts.py - do not edit. */\n")


def fetch(url, binary=False):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=60) as r:
        data = r.read()
    return data if binary else data.decode("utf-8")


def main():
    os.makedirs(OUT, exist_ok=True)
    keep = set()
    blocks_out = []

    for query, prefix in FAMILIES:
        css = fetch("https://fonts.googleapis.com/css2?" + query + "&display=swap")
        for subset, block in re.findall(
                r"/\*\s*([\w-]+)\s*\*/\s*(@font-face\s*\{[^}]*\})", css):
            if subset not in KEEP_SUBSETS:
                continue
            style = "italic" if "font-style: italic" in block else "regular"
            url = re.search(r"url\((https://[^)]+)\)", block).group(1)
            fname = f"{prefix}-{style}-{subset}.woff2"
            if fname not in keep:
                keep.add(fname)
                with open(os.path.join(OUT, fname), "wb") as f:
                    f.write(fetch(url, binary=True))
                print(f"  {fname}")
            blocks_out.append(f"/* {subset} */\n" + block.replace(url, fname))

    # drop anything left over from an earlier type pairing
    for fn in sorted(os.listdir(OUT)):
        if fn.endswith(".woff2") and fn not in keep:
            os.remove(os.path.join(OUT, fn))
            print(f"  removed {fn}")

    with open(os.path.join(OUT, "fonts.css"), "w", encoding="utf-8") as f:
        f.write(HEADER + "\n\n".join(blocks_out) + "\n")
    print(f"wrote fonts.css with {len(blocks_out)} @font-face blocks")


if __name__ == "__main__":
    main()
