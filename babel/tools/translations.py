def lookup_author(raw_author, book_id=None):
    """English author name given a CSV author field.

    Precedence:
      1. BOOKID_AUTHOR_OVERRIDES (for bookstore-placeholder rows)
      2. AUTHOR_TRANSLATIONS exact raw author match
      3. extract_english() salvage if the author already has Latin letters
      4. None — caller must decide what to do
    """
    if book_id and book_id in BOOKID_AUTHOR_OVERRIDES:
        return BOOKID_AUTHOR_OVERRIDES[book_id]
    if raw_author in AUTHOR_TRANSLATIONS:
        return AUTHOR_TRANSLATIONS[raw_author]
    en = extract_english(raw_author)
    if en:
        return en
    return None


import re as _re
_LATIN_RUN = _re.compile(r"[A-Za-z][A-Za-z \u00C0-\u024F\u0300-\u036F\.\-\'\u2022]{2,}")


def extract_english(raw_author):
    """Pull out the longest contiguous Latin-script run from a mixed author
    field.  Handles things like "斯拉沃热·齐泽克 Slavoj Zizek" → "Slavoj Zizek".
    """
    runs = _LATIN_RUN.findall(raw_author)
    if not runs:
        return None
    # pick the longest run (Latin author names are generally longer than
    # 2-letter Latin fragments that might appear next to CJK)
    return max(runs, key=len).strip()

